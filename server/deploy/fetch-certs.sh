#!/bin/sh
# ==============================================================
#  Забирает сертификаты серверов в клиент.
#
#  Клиент не хранит корневые сертификаты и не доверяет системным: он
#  ЗАШИВАЕТ себе сертификат каждого сервера и требует, чтобы сервер
#  предъявил именно его. Значит, файл в res://certs/ должен побайтово
#  совпадать с тем, что лежит на сервере.
#
#  Порядок строго такой:
#     1. на сервере:  sh gen-cert.sh <ip>        (выпуск, один раз)
#     2. здесь:       sh fetch-certs.sh <ip> …    (забор в репозиторий)
#     3. в сборке клиента файл уже лежит.
#
#  Перевыпуск сертификата на сервере БЕЗ повторного запуска этого
#  скрипта и новой сборки клиента = потеря связи с этим сервером у всех,
#  кто ещё не обновился. Поэтому скрипт без --force ничего не перезаписывает.
#
#  Использование:
#     sh fetch-certs.sh 85.209.2.116 31.56.196.114
#     sh fetch-certs.sh --force 85.209.2.116        # перезалить
#
#  Откуда берём: прямо с сервера по SSH. Отдельного HTTP-канала для
#  сертификатов не заводим — лишняя точка отказа и лишний открытый порт.
#
#  Про имя файла. Кладём <адрес дефисами>.crt, и это не прихоть:
#  только .crt движок Godot считает ресурсом, он проходит через импорт
#  и потому гарантированно оказывается внутри PCK собранной игры. Файл
#  .pem в сборку сам не попадает, и клиент уехал бы без сертификатов.
#  Содержимое остаётся PEM-текстом — X509Certificate такой файл разбирает.
#  Certs._load ищет сначала по id сервера, потом по адресу, так что имя
#  по адресу — рабочее и достаточное.
# ==============================================================

set -eu

DIR="$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)/certs"
SSH_OPTS="-o BatchMode=yes -o ConnectTimeout=10 -o StrictHostKeyChecking=accept-new"
REMOTE_CERT=/etc/digital-game/tls/cert.pem

FORCE=0
IPS=""
for arg in "$@"; do
  case "$arg" in
    --force) FORCE=1 ;;
    -*) echo "неизвестный ключ: $arg" >&2; exit 2 ;;
    *) IPS="$IPS $arg" ;;
  esac
done

if [ -z "${IPS# }" ]; then
  echo "укажите хотя бы один IP-адрес сервера, например:" >&2
  echo "    sh fetch-certs.sh 85.209.2.116 31.56.196.114" >&2
  exit 2
fi

mkdir -p "$DIR"

for ip in $IPS; do
  name="$(echo "$ip" | tr '.' '-')"
  tmp="$DIR/.fetch-$name.crt"

  if ! ssh $SSH_OPTS "root@$ip" "cat $REMOTE_CERT" > "$tmp" 2>/dev/null; then
    echo "не удалось забрать сертификат с $ip — пропускаю" >&2
    rm -f "$tmp"
    continue
  fi

  # Пустой или очевидно не-PEM файл — это не сертификат, а ошибка SSH
  # или пустая выдача. Класть такое в клиент нельзя: он будет зашит
  # и сломает подключение навсегда, а выглядит при этом как «файл есть».
  if ! grep -q "BEGIN CERTIFICATE" "$tmp"; then
    echo "с $ip пришёл не сертификат — пропускаю" >&2
    rm -f "$tmp"
    continue
  fi

  # Проверяем, что сертификат годится ИМЕННО для этого адреса. Ошибка
  # здесь означает, что на сервере выпущен сертификат для другого IP:
  # зашив его, мы получим клиент, который не подключается ни к одному
  # из двух серверов, и не поймём почему.
  if command -v openssl >/dev/null 2>&1; then
    if ! openssl x509 -in "$tmp" -noout -checkip "$ip" >/dev/null 2>&1; then
      echo "сертификат с $ip выдан НЕ для этого адреса — пропускаю" >&2
      openssl x509 -in "$tmp" -noout -subject -ext subjectAltName 2>/dev/null | sed 's/^/    /' >&2
      rm -f "$tmp"
      continue
    fi
  else
    echo "openssl не найден — проверку адреса пропускаю (риск: не тот адрес)" >&2
  fi

  dst="$DIR/$name.crt"
  if [ -f "$dst" ] && [ "$FORCE" -eq 0 ]; then
    if cmp -s "$tmp" "$dst"; then
      echo "$ip: $name.crt уже совпадает, ничего не делаю"
    else
      echo "$ip: ВНИМАНИЕ — $name.crt ОТЛИЧАЕТСЯ от серверного." >&2
      echo "         Если это перевыпуск: новые клиенты зашьют новый сертификат," >&2
      echo "         а старые перестанут подключаться. Проверьте, что так задумано." >&2
    fi
  else
    cp "$tmp" "$dst"
    echo "$ip: положил $name.crt"
    # Показываем, кому сертификат закончится: запись в этом файле —
    # единственное напоминание о сроке.
    if command -v openssl >/dev/null 2>&1; then
      openssl x509 -in "$dst" -noout -enddate 2>/dev/null | sed 's/^/    /'
    fi
  fi

  # Устаревшее имя от прежних запусков: .pem в сборку не уезжает, а
  # Certs._load сперва смотрит .crt, так что он просто вводил бы в
  # заблуждение при чтении репозитория.
  stale="$DIR/$name.pem"
  if [ -f "$stale" ]; then
    rm -f "$stale"
    echo "$ip: убрал устаревший $name.pem"
  fi

  rm -f "$tmp"
done

echo
echo "В $DIR:"
ls -1 "$DIR" 2>/dev/null || echo "  (пусто)"
echo
echo "Дальше: закоммить эти файлы и собрать клиент. Без них связь не установится."
