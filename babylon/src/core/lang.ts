export function setLang(code: LangCode): void {
  current = code;
}

export function getLang(): LangCode {
  return current;
}

export function t(key: string, ...args: Array<string | number>): string {
  const base = current === 'en' && EN[key] ? EN[key] : key;
  let out = base;
  let i = 0;
  out = out.replace(/%d|%s/g, () => String(args[i++] ?? ''));
  return out;
}

export function applyTitle(): void {
  document.title = t('Цифровая игра');
}
